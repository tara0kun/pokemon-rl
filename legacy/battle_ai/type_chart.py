    EFFECTIVENESS[ICE][ICE] = 0.5
    EFFECTIVENESS[ICE][GROUND] = 2.0
    EFFECTIVENESS[ICE][FLYING] = 2.0
    EFFECTIVENESS[ICE][DRAGON] = 2.0
    EFFECTIVENESS[ICE][STEEL] = 0.5

    # Ground
    EFFECTIVENESS[GROUND][FIRE] = 2.0
