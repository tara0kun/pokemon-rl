    EFFECTIVENESS[GRASS][GRASS] = 0.5
    EFFECTIVENESS[GRASS][POISON] = 0.5
    EFFECTIVENESS[GRASS][GROUND] = 2.0
    EFFECTIVENESS[GRASS][FLYING] = 0.5
    EFFECTIVENESS[GRASS][BUG] = 0.5
