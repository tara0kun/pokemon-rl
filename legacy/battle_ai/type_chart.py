def get_effectiveness(atk_type: int, def_type1: int, def_type2: int = -1) -> float:
    """攻撃タイプ vs 防御タイプ(1-2)の相性倍率を返す"""
    eff = EFFECTIVENESS.get(atk_type, {}).get(def_type1, 1.0)
    if def_type2 >= 0 and def_type2 != def_type1:
        eff *= EFFECTIVENESS.get(atk_type, {}).get(def_type2, 1.0)
    return eff


if __name__ == "__main__":
    # テスト
    print(f"Fire vs Grass: {get_effectiveness(FIRE, GRASS)}x")  # 2.0
