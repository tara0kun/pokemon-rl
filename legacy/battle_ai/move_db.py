from dataclasses import dataclass


@dataclass
class Move:
    id: int
    name: str
    type_id: int    # type_chart.pyのタイプID
    power: int      # 0 = ステータス技
    accuracy: int   # 0-100, 0=必中
    pp: int
    category: str   # "physical" / "special" / "status"
    # Gen3: physical/specialはタイプで決まる
    # physical: Normal,Fighting,Flying,Poison,Ground,Rock,Bug,Ghost,Steel
    # special: Fire,Water,Grass,Electric,Psychic,Ice,Dragon,Dark


# Gen3ではタイプで物理/特殊が決まる
PHYSICAL_TYPES = {0, 1, 2, 3, 4, 5, 6, 7, 8}  # Normal~Steel
SPECIAL_TYPES = {10, 11, 12, 13, 14, 15, 16, 17}  # Fire~Dark


def _cat(type_id: int, power: int) -> str:
    if power == 0:
        return "status"
    return "physical" if type_id in PHYSICAL_TYPES else "special"


